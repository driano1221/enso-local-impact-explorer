import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {sha256,conferirProva,conferirArquivo} from './www/verificar-core.js';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
const bytes=text=>new TextEncoder().encode(text),csv=bytes('year,temperature\n2025,22.3\n');
const expected=await sha256(csv),index=bytes(JSON.stringify({schema:'enso-csv-index-v1',entries:{query:expected}}));
const manifest=bytes(JSON.stringify({schema:'enso-public-bundle-v1',files:[{path:'csv-index.json',bytes:index.byteLength,sha256:await sha256(index)}]}));
const config={sha256:await sha256(manifest),transaction:'a'.repeat(64),account:'G'+'A'.repeat(55)};
const tx={successful:true,hash:config.transaction,source_account:config.account,memo_type:'hash',memo:Buffer.from(config.sha256,'hex').toString('base64'),ledger:123};
const checked=await conferirProva(manifest,index,tx,config);
assert.equal(checked.index.entries.query,expected);
assert.equal((await conferirArquivo(csv,expected)).matches,true);
assert.equal((await conferirArquivo(bytes('year,temperature\n2025,23.3\n'),expected)).matches,false);
await assert.rejects(()=>conferirProva(manifest,bytes('{}'),tx,config),/index/);
const rewritten=bytes(JSON.stringify({schema:'enso-public-bundle-v1',files:[]}));
await assert.rejects(()=>conferirProva(rewritten,index,tx,config),/manifest/);
const rewrittenHash=await sha256(rewritten);
await assert.rejects(()=>conferirProva(rewritten,index,tx,{...config,sha256:rewrittenHash}),/transaction/);
await assert.rejects(()=>conferirProva(manifest,index,{...tx,successful:false},config),/transaction/);
await assert.rejects(()=>conferirArquivo(csv,undefined),/query/);
console.log('PASS: browser cryptographic functions; correct file, changed value, changed index/manifest, failed transaction and unsupported query. Synthetic receipt, not a live-chain claim.');
